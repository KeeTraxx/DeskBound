def write_enemy_resources(cfg, V, setbar_id, dry_run):
    """One custom script per enemy — each its own module, so its own bank."""
    ids, paths, events, stale, written = {}, [], {}, [], set()
    actors = {ENEMY_ACTOR_SLOT: {"id": ENEMY_ACTOR_SLOT,
                                 "name": ENEMY_ACTOR_NAME}}
    if cfg.bars:
        actors[PLAYER_BAR_SLOT] = {"id": PLAYER_BAR_SLOT,
                                   "name": PLAYER_BAR_NAME}
    for e in cfg.enemies:
        name = f"{ENEMY_SCRIPT_PREFIX} {e.name}"
        script_id = stable_id(f"enemy_script_{e.id}")
        resource = {
            "_resourceType": "script",
            "id": script_id,
            "name": name,
            "description": f"{e.name}'s half of the battle. {GENERATED_MARK}",
            "variables": {ENEMY_PHASE_SLOT: {"id": ENEMY_PHASE_SLOT,
                                             "name": "Phase",
                                             "passByReference": False}},
            "actors": actors,
            "symbol": f"script_enemy_{e.id}",
            "script": build_enemy_script(cfg, V, e, setbar_id),
        }
        path = os.path.join(ROOT, "project", "scripts",
                            f"{slugify(name)}.gbsres")
        if not dry_run:
            save_json(path, resource)
        ids[e.id] = script_id
        events[script_id] = resource["script"]
        paths.append((name, path))
        written.add(os.path.abspath(path))

    # Renaming or removing an enemy would otherwise leave its script behind,
    # still compiling into a bank of its own. Only files this tool stamped are
    # ever removed — a hand-written script that happens to start with the same
    # word is left alone.
    for path in glob.glob(os.path.join(SCRIPTS_DIR, "*.gbsres")):
        if os.path.abspath(path) in written:
            continue
        data = load_json(path)
        if data.get("description", "").endswith(GENERATED_MARK) and \
                data.get("name", "").startswith(ENEMY_SCRIPT_PREFIX + " "):
            stale.append(os.path.relpath(path, ROOT))
            if not dry_run:
                os.remove(path)
    return ids, paths, events, stale


