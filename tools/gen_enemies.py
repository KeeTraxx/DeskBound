def load_json(path):
    with open(path) as f:
        return json.load(f)


def save_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=2)


def load_variables():
    """name -> variable id, read from the project so ids can never drift."""
    path = os.path.join(ROOT, "project", "variables.gbsres")
    if not os.path.exists(path):
        fail(f"missing {path}")
    names = {}
    for v in load_json(path).get("variables", []):
        names[v["name"]] = v["id"]
    missing = [n for n in REQUIRED_VARS if n not in names]
    if missing:
        fail("project/variables.gbsres is missing required variables: "
             + ", ".join(missing))
    return names


SPRITE_DIR = os.path.join(ROOT, "assets", "sprites")


SCRIPTS_DIR = os.path.join(ROOT, "project", "scripts")


def load_scripts():
    """name -> custom script resource, for hooks written by hand in the GUI."""
    scripts = {}
    for path in glob.glob(os.path.join(SCRIPTS_DIR, "*.gbsres")):
        data = load_json(path)
        if data.get("_resourceType") == "script" and data.get("name"):
            scripts[data["name"]] = data
    return scripts


def load_sprites():
    """png file -> sprite sheet id, keyed the way enemies.yaml names sprites.

    The key is the path under assets/sprites/ ("actor.png", or
    "enemies/coffee.png" in a subfolder), not GB Studio's internal sprite
    *name*, so the YAML points at a file you can actually open.
    """
    sprites = {}
    pattern = os.path.join(SPRITE_DIR, "**", "*.png.gbsres")
    for sidecar in glob.glob(pattern, recursive=True):
        png = sidecar[:-len(".gbsres")]
        if not os.path.exists(png):
            continue  # sidecar without its image; GB Studio ignores it too
        sprites[os.path.relpath(png, SPRITE_DIR)] = load_json(sidecar)["id"]
    return sprites


# --------------------------------------------------------------- yaml loading
def var_ref(var_id):
    """Text interpolation token for a global, e.g. "$13$"."""
    return f"${int(var_id):02d}$" if str(var_id).isdigit() else f"${var_id}$"


class Substituter:
    """Replaces {damage}-style placeholders in any text with variable refs.

    Lets the YAML say "It loses {damage} Energy." instead of "$13$", which
    would otherwise bake variable *indices* into the writing.
    """

    def __init__(self, variables):
        self.tokens = {
            name: var_ref(variables[name]) for name in
            ("player_energy", "player_energy_max", "enemy_energy",
             "enemy_energy_max", "battle_turn_count", "enemy_id")
        }
        self.tokens["damage"] = var_ref(variables["battle_damage"])
        self.tokens["turn"] = var_ref(variables["battle_turn_count"])

    def __call__(self, body):
        if isinstance(body, list):
            return [self(line) for line in body]
        if not isinstance(body, str):
            fail(f"expected text, got {body!r}")
        return re.sub(r"\{(\w+)\}",
                      lambda m: self.tokens.get(m.group(1), m.group(0)), body)


def as_variants(value, where):
    """Normalise a text field to [[step, ...], ...] — variants of steps.

    Canonical form is a list of lists: one variant is picked at random, then
    its steps play in order. A flat list of strings is one variant with those
    steps, and a bare string is one variant with one step.
    """
    if isinstance(value, str):
        return [[value]]
    if not isinstance(value, list) or not value:
        fail(f"{where}: expected a non-empty list of dialogue variants")
    if all(isinstance(v, str) for v in value):
        return [list(value)]
    if not all(isinstance(v, list) for v in value):
        fail(f"{where}: mixes strings and lists — write every variant as its "
             "own list of steps")
    variants = []
    for i, variant in enumerate(value):
        if not variant or not all(isinstance(s, str) for s in variant):
            fail(f"{where}[{i}]: a variant must be a non-empty list of strings")
        variants.append(list(variant))
    return variants


def dialogue(value, where, subst):
    """Validate a text field's shape, then interpolate its placeholders."""
    return [[subst(step) for step in variant]
            for variant in as_variants(value, where)]


def parse_range(value, where):
    """Accept 5, "3-6" or [3, 6] and return an inclusive (lo, hi)."""
    if isinstance(value, bool):
        fail(f"{where}: expected a damage range, got {value!r}")
    if isinstance(value, int):
        lo = hi = value
    elif isinstance(value, str):
        m = re.fullmatch(r"\s*(\d+)\s*(?:-\s*(\d+)\s*)?", value)
        if not m:
            fail(f"{where}: bad damage range {value!r} (use 5 or \"3-6\")")
        lo = int(m.group(1))
        hi = int(m.group(2)) if m.group(2) else lo
    elif isinstance(value, list) and len(value) == 2 and all(
            isinstance(v, int) for v in value):
        lo, hi = value
    else:
        fail(f"{where}: bad damage range {value!r} (use 5, \"3-6\" or [3, 6])")
    if lo > hi:
        fail(f"{where}: damage range {value!r} is backwards")
    if hi > MAX_VAR_VALUE:
        fail(f"{where}: damage {hi} exceeds the 16-bit variable range")
    return lo, hi


def damage_value(lo, hi):
    """Script value for a uniform roll in [lo, hi]. rnd(n) yields 0..n-1."""
    if lo == hi:
        return num(lo)
    return add(num(lo), rnd(num(hi - lo + 1)))


def require(mapping, key, where):
    if key not in mapping:
        fail(f"{where}: missing required key '{key}'")
    return mapping[key]


class Effect:
    """One ACT verb's result against one enemy, or one enemy move."""

    def __init__(self, raw, where, subst):
        if isinstance(raw, dict):
            self.lo, self.hi = parse_range(require(raw, "damage", where), where)
            self.text = (dialogue(raw["text"], f"{where} text", subst)
                         if "text" in raw else None)
            unknown = set(raw) - {"damage", "text"}
            if unknown:
                fail(f"{where}: unknown keys {sorted(unknown)}")
        else:
            self.lo, self.hi = parse_range(raw, where)
            self.text = None


class Enemy:
    def __init__(self, raw, index, actions, sprites, subst):
        if not isinstance(raw, dict):
            fail(f"enemies[{index}]: expected a mapping")
        self.name = require(raw, "name", f"enemies[{index}]")
        where = f"enemy '{self.name}'"
        # Ids may start at 0, which suits an overworld that picks a fight with
        # a bare rnd(n). Left out, an id is the enemy's position in the list
        # counting from 1, so omitting ids never renumbers an existing project.
        self.id = raw.get("id", index + 1)
        if not isinstance(self.id, int) or isinstance(self.id, bool) \
                or self.id < 0:
            fail(f"{where}: id must be 0 or a positive integer")

        sprite_name = require(raw, "sprite", where)
        if sprite_name not in sprites:
            hint = ""
            if f"{sprite_name}.png" in sprites:
                hint = f" Did you mean '{sprite_name}.png'?"
            fail(f"{where}: no sprite file 'assets/sprites/{sprite_name}'."
                 f"{hint} Available: " + ", ".join(sorted(sprites)))
        self.sprite_id = sprites[sprite_name]
        self.sprite_name = sprite_name

        self.energy = require(raw, "energy", where)
        if not isinstance(self.energy, int) or not (
                0 < self.energy <= MAX_VAR_VALUE):
            fail(f"{where}: energy must be a positive integer")

        self.intro = dialogue(require(raw, "intro", where),
                              f"{where} intro", subst)
        self.look = dialogue(require(raw, "look", where),
                             f"{where} look", subst)
        self.defeat = dialogue(require(raw, "defeat", where),
                               f"{where} defeat", subst)

        take_damage = require(raw, "take_damage", where)
        if not isinstance(take_damage, dict):
            fail(f"{where}: take_damage must be a mapping of action -> damage")
        unknown = [a for a in take_damage if a not in actions]
        if unknown:
            fail(f"{where}: take_damage has actions not in the top-level "
                 f"'actions' list: {unknown}")
        missing = [a for a in actions if a not in take_damage]
        if missing:
            fail(f"{where}: take_damage is missing {missing}")
        self.take_damage = {
            action: Effect(take_damage[action],
                           f"{where} take_damage.{action}", subst)
            for action in actions
        }

        moves = require(raw, "moves", where)
        if not isinstance(moves, list) or not moves:
            fail(f"{where}: moves must be a non-empty list")
        self.moves = []
        for i, move in enumerate(moves):
            if not isinstance(move, dict) or "text" not in move:
                fail(f"{where} moves[{i}]: expected a mapping with 'text' "
                     "and 'damage'")
            self.moves.append(Effect(move, f"{where} moves[{i}]", subst))

        self.reward = self._read_reward(raw.get("reward"), where, subst)

        self.can_flee = raw.get("can_flee", True)
        self.flee_blocked = raw.get("flee_blocked")
        if self.flee_blocked:
            self.flee_blocked = dialogue(self.flee_blocked,
                                         f"{where} flee_blocked", subst)
        self.win_flag = raw.get("win_flag")

        unknown = set(raw) - {
            "id", "name", "sprite", "energy", "intro", "look", "defeat",
            "take_damage", "moves", "can_flee", "flee_blocked", "win_flag",
            "reward"}
        if unknown:
            fail(f"{where}: unknown keys {sorted(unknown)}")

    @staticmethod
    def _read_reward(reward, where, subst):
        """What beating this enemy gives back. Only applied on a win."""
        if not reward:
            return None
        if not isinstance(reward, dict):
            fail(f"{where} reward: expected a mapping of stat -> amount")
        unknown = set(reward) - set(REWARD_VARS) - {"text"}
        if unknown:
            fail(f"{where} reward: unknown keys {sorted(unknown)}. "
                 f"Stats: {', '.join(REWARD_VARS)}")
        out = {"text": dialogue(reward["text"], f"{where} reward.text", subst)
                       if "text" in reward else None}
        for stat in REWARD_VARS:
            if stat in reward:
                lo, hi = parse_range(reward[stat], f"{where} reward.{stat}")
                if hi < 1:
                    fail(f"{where} reward.{stat}: a reward must be able to "
                         "give at least 1")
                out[stat] = (lo, hi)
        if not any(stat in out for stat in REWARD_VARS) and not out["text"]:
            fail(f"{where} reward: empty — give a stat or some text, or drop "
                 "the key")
        return out


class Config:
    def __init__(self, raw, variables, sprites, scripts):
        if not isinstance(raw, dict):
            fail("enemies.yaml must be a mapping")
        subst = Substituter(variables)

        enemies_raw = require(raw, "enemies", "enemies.yaml")
        if not isinstance(enemies_raw, list) or not enemies_raw:
            fail("enemies.yaml: 'enemies' must be a non-empty list")

        self.actions = raw.get("actions")
        if self.actions is None:
            first = enemies_raw[0]
            self.actions = list(first.get("take_damage", {}))
        if not self.actions or not all(isinstance(a, str) for a in self.actions):
            fail("enemies.yaml: 'actions' must be a list of verb names")
        if len(self.actions) > 8:
            fail("enemies.yaml: GB Studio menus hold at most 8 options, "
                 f"got {len(self.actions)} actions")

        self.enemies = [Enemy(e, i, self.actions, sprites, subst)
                        for i, e in enumerate(enemies_raw)]
        seen_ids, seen_names = {}, {}
        for e in self.enemies:
            if e.id in seen_ids:
                fail(f"enemy id {e.id} used by both '{seen_ids[e.id]}' and "
                     f"'{e.name}'")
            seen_ids[e.id] = e.name
            if e.name in seen_names:
                fail(f"duplicate enemy name '{e.name}'")
            seen_names[e.name] = True

        self.messages = dict(DEFAULT_MESSAGES)
        self.messages.update(raw.get("messages") or {})
        self.messages = {k: dialogue(v, f"messages.{k}", subst)
                         for k, v in self.messages.items()}

        self.menu = dict(DEFAULT_MENU)
        self.menu.update(raw.get("menu") or {})

        self.flee = dict(DEFAULT_FLEE)
        self.flee.update(raw.get("flee") or {})
        if not isinstance(self.flee["out_of"], int) or self.flee["out_of"] < 1:
            fail("flee.out_of must be a positive integer")
        if not isinstance(self.flee["chance"], int) or not (
                0 <= self.flee["chance"] <= self.flee["out_of"]):
            fail("flee.chance must be between 0 and flee.out_of")
        for key in ("success", "failed", "blocked"):
            self.flee[key] = dialogue(self.flee[key], f"flee.{key}", subst)

        self.lose = dialogue(raw.get("lose") or [
            "You have run out of\nEnergy.",
            "You quietly gather\nyour things.",
        ], "lose", subst)

        for e in self.enemies:
            for stat in (e.reward or {}):
                if stat == "text":
                    continue
                if REWARD_VARS[stat] not in variables:
                    fail(f"enemy '{e.name}' reward.{stat}: needs a variable "
                         f"named '{REWARD_VARS[stat]}' in "
                         "project/variables.gbsres")

        self.win_flags = {}
        for e in self.enemies:
            if e.win_flag:
                if e.win_flag not in variables:
                    fail(f"enemy '{e.name}': win_flag '{e.win_flag}' is not a "
                         "variable in project/variables.gbsres")
                self.win_flags[e.id] = variables[e.win_flag]

        unknown = set(raw) - {"enemies", "actions", "messages",
                              "menu", "flee", "lose", "bars", "hooks"}
        if unknown:
            fail(f"enemies.yaml: unknown top-level keys {sorted(unknown)}")

        self.hooks = self._read_hooks(raw.get("hooks"), scripts)
        self.bars = self._read_bars(raw.get("bars"), sprites)

    def _read_hooks(self, hooks, scripts):
        """Optional hand-written scripts to call when the battle moves a value.

        Resolved by name from project/scripts/ so the script stays yours: this
        tool reads its parameter list and never rewrites it.
        """
        if not hooks:
            return {}
        if not isinstance(hooks, dict):
            fail("enemies.yaml: 'hooks' must be a mapping")
        supported = ("player_changed", "player_fainted")
        unknown = set(hooks) - set(supported)
        if unknown:
            fail(f"hooks: unknown keys {sorted(unknown)}. Supported: "
                 + ", ".join(supported))
        resolved = {}
        for key, name in hooks.items():
            if name is None:
                continue
            if name not in scripts:
                fail(f"hooks.{key}: no script named '{name}' in "
                     "project/scripts/. Available: "
                     + ", ".join(sorted(scripts)))
            script = scripts[name]
            if name in (SCRIPT_NAME, SETBAR_NAME):
                fail(f"hooks.{key}: '{name}' is generated by this tool — "
                     "calling it would recurse")
            # Hooks are called with no arguments, so anything the script
            # declares as a parameter would be left unbound — and an unbound
            # arg does not fail the GB Studio build, it silently compiles to
            # whichever variable the context defaults to.
            params = list(script.get("variables") or {}) + [
                f"actor {a}" for a in (script.get("actors") or {})]
            if params:
                fail(f"hooks.{key}: '{name}' declares parameters {params}, but "
                     "a hook is called with none — it reads globals directly. "
                     "In GB Studio, change the script to reference the global "
                     "variable instead of V0 and the parameter disappears.")
            resolved[key] = {"name": name, "id": script["id"]}
        return resolved

    def _read_bars(self, bars, sprites):
        """Optional Energy meters. Absent 'bars:' means none are generated.

        GB Studio has no hook that fires when a variable changes, so each bar
        is an actor that polls its variable in its own On Update script.
        """
        if not bars:
            return None
        if not isinstance(bars, dict):
            fail("enemies.yaml: 'bars' must be a mapping")
        sprite = require(bars, "sprite", "bars")
        if sprite not in sprites:
            fail(f"bars: no sprite file 'assets/sprites/{sprite}'. Available: "
                 + ", ".join(sorted(sprites)))
        frames = bars.get("frames", 17)
        if not isinstance(frames, int) or frames < 2:
            fail("bars.frames must be an integer of 2 or more (one sprite "
                 "frame per fill level, empty through full)")
        # frame = energy * (frames - 1) / max, computed in 16-bit ints.
        # Only the enemies can be checked here; the player's Energy is a
        # global set by the overworld, so keep it under this ceiling too.
        headroom = MAX_VAR_VALUE // (frames - 1)
        for e in self.enemies:
            if e.energy > headroom:
                fail(f"bars: enemy '{e.name}' energy {e.energy} × "
                     f"{frames - 1} frames overflows a 16-bit variable")
        unknown = set(bars) - {"sprite", "frames", "width", "height"}
        if unknown:
            fail(f"bars: unknown keys {sorted(unknown)}")
        return {
            "sprite": sprite,
            "sprite_id": sprites[sprite],
            "frames": frames,
        }


def build_setbar_script(cfg):
    """The "SetBar" custom script: show `value`/`max` on a bar actor.

    Kept as its own script rather than inlined so a hand-written script can
    refresh a bar too — drag SetBar in, pick the actor, pass the two values.
    """
    return [
        comment("Generated by tools/gen_enemies.py — sets a Energy bar's "
                "frame from a value and its maximum"),
        actor_set_frame("0", bar_fill_expression(cfg.bars["frames"],
                                                 SETBAR_VALUE_SLOT,
                                                 SETBAR_MAX_SLOT)),
    ]


def make_hook(cfg):
    """Emit a call to a hand-written hook.

    Hooks take no arguments: a custom script reads globals directly (only
    V0-V9 are parameters), so the hook just looks at player_energy itself.
    """

    def hook(key):
        spec = cfg.hooks.get(key)
        return [call_custom(spec["id"])] if spec else []

    return hook


def make_set_bar(cfg, V, setbar_id):
    """Emit a SetBar call, forwarding one of BattleScript's bar parameters."""

    def set_bar(slot, value_name, max_name):
        if not cfg.bars:
            return []
        return [call_custom(setbar_id, {
            f"$actor[0]$": slot,
            f"$variable[{SETBAR_VALUE_SLOT}]$": var(V[value_name]),
            f"$variable[{SETBAR_MAX_SLOT}]$": var(V[max_name]),
        })]

    return set_bar


# ----------------------------------------------------------- script generation
def make_emitters(cfg, V, setbar_id):
    """The pieces both builders need: dialogue, bars, hooks."""
    say = make_say(V["battle_temp"])
    set_bar = make_set_bar(cfg, V, setbar_id)
    hook = make_hook(cfg)

    def player_energy_changed():
        return (set_bar(PLAYER_BAR_SLOT, "player_energy", "player_energy_max")
                + hook("player_changed"))

    return say, set_bar, player_energy_changed, hook


def build_enemy_script(cfg, V, e, setbar_id):
    """One enemy's half of the fight, dispatched on a phase parameter.

    Everything that scales with the roster lives here — dialogue, per-verb
    responses, moves, the reward — so each enemy occupies its own module and
    therefore its own 16KB bank. BattleScript keeps only the turn loop.
    """
    say, set_bar, player_energy_changed, _ = make_emitters(cfg, V, setbar_id)

    # NAME: the name plate on its own, so BattleScript can put it back.
    # Every message and every menu takes its glyphs from the same 52-tile ring
    # (see text_draw), and the plate is drawn first, which makes it the first
    # thing the ring laps onto. Redrawing hands it fresh tiles at the point it
    # matters — BattleScript calls this phase at the top of each turn.
    name_plate = [text_draw(e.name, NAME_X, NAME_Y)]

    # SETUP: stats, sprite, name plate and the opening line.
    setup = [
        set_var(V["enemy_energy"], num(e.energy)),
        set_var(V["enemy_energy_max"], num(e.energy)),
        actor_set_sprite(ENEMY_ACTOR_SLOT, e.sprite_id),
    ] + name_plate + say(e.intro)

    # ACT: what each verb does to this enemy. Sets battle_damage; BattleScript
    # applies it, so the enemy bar and the hit line stay in one place.
    act_cases = []
    for i, action in enumerate(cfg.actions):
        effect = e.take_damage[action]
        body = say(effect.text) if effect.text else []
        body.append(set_var(V["battle_damage"],
                            damage_value(effect.lo, effect.hi)))
        act_cases.append((i + 1, body))
    act = dispatch(var(V["battle_act_choice"]), act_cases)

    # FLEE: a dice roll, or a flat refusal for an enemy you cannot leave.
    if e.can_flee:
        flee = [
            set_var(V["battle_temp"], rnd(num(cfg.flee["out_of"]))),
            if_value(
                lt(var(V["battle_temp"]), num(cfg.flee["chance"])),
                say(cfg.flee["success"])
                + [set_var(V["battle_result"], num(RESULT_FLED))],
                say(cfg.flee["failed"]),
            ),
        ]
    else:
        flee = say(e.flee_blocked or cfg.flee["blocked"])

    # MOVE: the enemy's turn.
    move_cases = []
    for i, move in enumerate(e.moves):
        hit = say(move.text) + [
            set_var(V["battle_damage"], damage_value(move.lo, move.hi)),
            set_var(V["player_energy"],
                    vmax(num(0), sub(var(V["player_energy"]),
                                     var(V["battle_damage"])))),
        ] + player_energy_changed()
        hit.append(if_value(gt(var(V["battle_damage"]), num(0)),
                            say(cfg.messages["player_hit"])))
        move_cases.append((i, hit))
    # catch_all: the roll covers every move, and a move's own dialogue may
    # re-roll battle_temp, so the last case must not be re-tested.
    moves = ([set_var(V["battle_temp"], rnd(num(len(e.moves))))]
             + dispatch(var(V["battle_temp"]), move_cases, catch_all=True))

    defeat = say(e.defeat) + reward_events(cfg, V, e, say,
                                           player_energy_changed)
    if e.id in cfg.win_flags:
        defeat.append(set_var(cfg.win_flags[e.id], num(1)))

    return [
        comment(f"{e.name} — generated by tools/gen_enemies.py from "
                "enemies.yaml; edits here will be overwritten"),
    ] + dispatch(var(ENEMY_PHASE_SLOT), [
        (PHASE_SETUP, setup),
        (PHASE_ACT, act),
        (PHASE_NAME, name_plate),
        (PHASE_LOOK, say(e.look)),
        (PHASE_FLEE, flee),
        (PHASE_MOVE, moves),
        (PHASE_DEFEAT, defeat),
    ])


def reward_events(cfg, V, e, say, player_energy_changed):
    """Apply a win's stat gains, then show the flavour line.

    Order matters: the gains land before the text, so the bar has already
    grown by the time the player reads about it. A max_energy gain raises
    current Energy by the same amount, so widening the tank never leaves the
    bar looking emptier than it was a moment ago.
    """
    reward = e.reward
    if not reward:
        return []

    def amount(stat):
        """The gain as a script value, rolling a range into battle_temp.

        battle_temp is free here — the fight is over and nothing is
        dispatching on it — but a range must be rolled once and reused, not
        re-rolled per use.
        """
        lo, hi = reward[stat]
        if lo == hi:
            return [], num(lo)
        return ([set_var(V["battle_temp"], damage_value(lo, hi))],
                var(V["battle_temp"]))

    out, touched_energy = [], False
    if "max_energy" in reward:
        roll, value = amount("max_energy")
        out += roll + [
            set_var(V["player_energy_max"],
                    add(var(V["player_energy_max"]), value)),
            # same amount into current Energy, so the bar keeps its fill
            set_var(V["player_energy"], add(var(V["player_energy"]), value)),
        ]
        touched_energy = True
    if "energy" in reward:
        roll, value = amount("energy")
        out += roll + [
            set_var(V["player_energy"],
                    vmin(var(V["player_energy_max"]),
                         add(var(V["player_energy"]), value))),
        ]
        touched_energy = True
    if "brains" in reward:
        roll, value = amount("brains")
        out.append(set_var(V["player_brains"],
                           add(var(V["player_brains"]), value)))
    if touched_energy:
        out += player_energy_changed()
    if reward["text"]:
        out += say(reward["text"])
    return out


def build_battle_script(cfg, V, setbar_id, enemy_script_ids):
    """The turn loop. Everything enemy-specific is a call into its script."""
    say, set_bar, player_energy_changed, hook = make_emitters(
        cfg, V, setbar_id)

    def enemy_phase(phase):
        """Branch on enemy_id and run that enemy's script at `phase`."""
        args = {f"$actor[{ENEMY_ACTOR_SLOT}]$": ENEMY_ACTOR_SLOT,
                f"$variable[{ENEMY_PHASE_SLOT}]$": num(phase)}
        if cfg.bars:
            args[f"$actor[{PLAYER_BAR_SLOT}]$"] = PLAYER_BAR_SLOT
        return dispatch(var(V["enemy_id"]),
                        [(e.id, [call_custom(enemy_script_ids[e.id], args)])
                         for e in cfg.enemies])

    s = [comment("Generated by tools/gen_enemies.py from enemies.yaml — "
                 "edits made here will be overwritten")]

    # --- setup: look up the enemy the overworld asked for -------------------
    s.append(comment("Load enemy from enemy_id"))
    s += enemy_phase(PHASE_SETUP)
    s += set_bar(ENEMY_BAR_SLOT, "enemy_energy", "enemy_energy_max")

    s += [
        # player_energy / player_energy_max are NOT set here: they are
        # global, owned by the overworld, and carry across battles.
        set_var(V["battle_turn_count"], num(0)),
        set_var(V["battle_result"], num(RESULT_ONGOING)),
    ] + player_energy_changed()

    # --- one round ----------------------------------------------------------
    turn = [
        set_var(V["battle_turn_count"],
                add(var(V["battle_turn_count"]), num(1))),
        set_var(V["battle_damage"], num(0)),
        # "status" is optional and unset by default — the bars report Energy.
        *(say(cfg.messages["status"]) if "status" in cfg.messages else []),
        # Repaint the name plate last, so it holds the newest tiles in the
        # glyph ring when the menu opens. The menu's own labels are far short
        # of a full lap, so the plate survives the one screen the player
        # actually sits and looks at.
        *enemy_phase(PHASE_NAME),
        menu(V["battle_menu_choice"],
             [cfg.menu["act"], cfg.menu["look"], cfg.menu["flee"]],
             layout="menu"),
    ]

    act = [menu(V["battle_act_choice"], cfg.actions, layout="dialogue")]
    act += enemy_phase(PHASE_ACT)
    act += [
        set_var(V["enemy_energy"],
                vmax(num(0), sub(var(V["enemy_energy"]),
                                 var(V["battle_damage"])))),
    ] + set_bar(ENEMY_BAR_SLOT, "enemy_energy", "enemy_energy_max") + [
        if_value(gt(var(V["battle_damage"]), num(0)),
                 say(cfg.messages["hit"]),
                 say(cfg.messages["no_effect"])),
    ]

    turn.append(if_value(
        eq(var(V["battle_menu_choice"]), num(1)), act,
        [if_value(eq(var(V["battle_menu_choice"]), num(2)),
                  enemy_phase(PHASE_LOOK), enemy_phase(PHASE_FLEE))]))

    # Win check runs before the enemy replies, so a killing blow ends it.
    turn.append(if_value(lte(var(V["enemy_energy"]), num(0)),
                         [set_var(V["battle_result"], num(RESULT_WIN))]))

    # --- enemy turn (skipped after LOOK, a successful flee, or a win) -------
    turn.append(if_value(
        vand(ne(var(V["battle_menu_choice"]), num(2)),
             eq(var(V["battle_result"]), num(RESULT_ONGOING))),
        enemy_phase(PHASE_MOVE)))

    turn.append(if_value(lte(var(V["player_energy"]), num(0)),
                         [set_var(V["battle_result"], num(RESULT_LOST))]))

    s.append(loop_while(eq(var(V["battle_result"]), num(RESULT_ONGOING)), turn))

    # --- resolution ---------------------------------------------------------
    # Out of Energy: say the line, then hand over to the overworld's hook —
    # which is where going home and sleeping belongs (DESIGN.md 9.2). If that
    # hook switches scenes, the pop below never runs: a scene change kills
    # every running script.
    lost = say(cfg.lose) + hook("player_fainted")

    s.append(if_value(
        eq(var(V["battle_result"]), num(RESULT_WIN)), enemy_phase(PHASE_DEFEAT),
        [if_value(eq(var(V["battle_result"]), num(RESULT_LOST)), lost)]))

    # Return to whichever scene pushed its state before the fight.
    s.append(pop_state())
    return s


